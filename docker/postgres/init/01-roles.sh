#!/bin/sh
# Crée le rôle applicatif (sans SUPERUSER) et la base de test.
# Exécuté une seule fois par l'image postgres, à l'initialisation du volume.
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-SQL
  CREATE ROLE ${EPAROLE_APP_USER} LOGIN PASSWORD '${EPAROLE_APP_PASSWORD}'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
  CREATE DATABASE ${EPAROLE_TEST_DB} OWNER ${POSTGRES_USER};
SQL

for db in "$POSTGRES_DB" "$EPAROLE_TEST_DB"; do
  psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$db" <<-SQL
    REVOKE ALL ON SCHEMA public FROM PUBLIC;
    GRANT USAGE ON SCHEMA public TO ${EPAROLE_APP_USER};
    ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public
      GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${EPAROLE_APP_USER};
    ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public
      GRANT USAGE, SELECT ON SEQUENCES TO ${EPAROLE_APP_USER};
SQL
done
